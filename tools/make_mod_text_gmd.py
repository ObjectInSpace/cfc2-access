"""Generate src/mod_text_gmd.h: the words the mod speaks that the collection
itself already translates, copied from its 14 menu message tables (msg.arc).

Each entry names the GMD label it comes from, so the wording always matches
what the game shows in that language:
  MT_NORMAL       OPT_Z3U_GS_00     "Normal" (Alpha 3 game speed)
  MT_TURBO        OPT_CVS2_GS_01    "Turbo 1" with the trailing number removed
  MT_RANDOM       EXOPT_PWS2_01_01  "Random"
  MT_OPPONENT     VS_PLAYER         "Opponent"
  MT_PLAYER_N     LOBBY_PLAYER_1    "Player 1" with the number made {0}
  MT_STAGE_PREFIX CHARA_CHANGE_ST   "Stage: "

Usage: python tools/make_mod_text_gmd.py [--check]
"""
import argparse
from pathlib import Path
import re
import sys

from gmd import iter_gmds, parse_gmd

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / 'src' / 'mod_text_gmd.h'
ARC = Path(r'C:\Program Files (x86)\Steam\steamapps\common\CAPCOM FIGHTING COLLECTION 2'
           r'\nativeDX11x64\arc\pc\msg.arc')
LANGS = ['jpn', 'eng', 'fre', 'ita', 'ger', 'spa', 'oth', 'kor', 'pol', 'por', 'rus', 'chT', 'chS', 'ara']


def strip_number(text):
    """'Turbo 1' -> 'Turbo'; '加速1' -> '加速'. Refuses a text without one."""
    out = re.sub(r'\s*1\s*$', '', text)
    if out == text:
        raise SystemExit(f'No trailing 1 in {text!r}')
    return out


def number_slot(text):
    """'Player 1' -> 'Player {0}'. Exactly one '1' is required."""
    if text.count('1') != 1:
        raise SystemExit(f'Expected exactly one 1 in {text!r}')
    return text.replace('1', '{0}')


ENTRIES = [
    ('MT_NORMAL', 'OPT_Z3U_GS_00', lambda t: t),
    ('MT_TURBO', 'OPT_CVS2_GS_01', strip_number),
    ('MT_RANDOM', 'EXOPT_PWS2_01_01', lambda t: t),
    ('MT_OPPONENT', 'VS_PLAYER', lambda t: t),
    ('MT_PLAYER_N', 'LOBBY_PLAYER_1', number_slot),
    ('MT_STAGE_PREFIX', 'CHARA_CHANGE_ST', lambda t: t),
]


def c_wide(text):
    out = []
    for ch in text:
        if ch in '\\"':
            out.append('\\' + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append(f'\\x{ord(ch):04x}" L"')
    return 'L"' + ''.join(out) + '"'


def build():
    tables = {}
    for name, raw in iter_gmds(ARC):
        lang = name.replace(chr(92), '/').split('/')[-1].replace('menu_', '')
        tables[lang] = parse_gmd(raw)[2]
    missing = [l for l in LANGS if l not in tables]
    if missing:
        raise SystemExit(f'Missing languages: {missing}')
    lines = [
        '/* Generated by tools/make_mod_text_gmd.py from msg.arc -- do not edit.',
        ' * The collection\'s own translations of words the mod speaks; each row',
        ' * names its GMD label. Language order is MT_LANGS in mod_text.h. */',
        '#ifndef CFC2_MOD_TEXT_GMD_H',
        '#define CFC2_MOD_TEXT_GMD_H',
        '#define MT_GMD_ROWS \\',
    ]
    for ident, label, fix in ENTRIES:
        texts = []
        for lang in LANGS:
            if label not in tables[lang] or not tables[lang][label].strip():
                raise SystemExit(f'{label} missing in {lang}')
            texts.append(c_wide(fix(tables[lang][label])))
        lines.append(f'    /* {label} */ \\')
        lines.append(f'    MT_GMD_ROW({ident}, {", ".join(texts)}) \\')
    lines.append('')
    lines.append('#endif')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding='utf-8') != text:
            sys.exit(f'Stale: {OUT}')
        print('mod_text_gmd.h is current.')
        return
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'Wrote {OUT}')


if __name__ == '__main__':
    main()
