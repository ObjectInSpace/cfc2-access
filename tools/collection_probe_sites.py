"""Generate whole-body fingerprints for the opt-in boundary event probe."""
from pathlib import Path
import argparse
from collection_lifecycle_audit import Dump, DEFAULT_DUMP

# Order is the probe's site enum. These bodies use only the stated incoming
# integer arguments; the load callback's observed result is AL (boolean).
SITES = (
    ('outer_update', 0x14003A290, 0x14003A79D),
    ('snapshot_load', 0x1400B6D50, 0x1400B6DBA),
    ('root_registration', 0x1400B6570, 0x1400B65DE),
    ('game_cleanup', 0x14004ADC0, 0x14004ADE9),
    ('screen_release', 0x140037140, 0x140037292),
)


def fingerprint(data):
    value = 0xcbf29ce484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001b3) & 0xffffffffffffffff
    return value


def render(directory=DEFAULT_DUMP):
    dump = Dump(directory)
    rows = ['/* Generated by tools/collection_probe_sites.py. Do not hand-edit. */',
            'static const probe_site g_sites[] = {']
    for name, start, end in SITES:
        dump.instructions(start, end)
        rows.append(f'    {{"{name}", UINT64_C({start:#x}), {end-start}, '
                    f'UINT64_C({fingerprint(dump.read(start,end-start)):#x})}},')
    return '\n'.join(rows + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixtures', type=Path)
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'src/collection_probe_sites.inc'
    if args.fixtures:
        dump = Dump(DEFAULT_DUMP)
        rows = ['/* Test-only pinned code bytes. Never executed. */']
        for index, (_, start, end) in enumerate(SITES):
            rows.append(f'static const unsigned char fixture_{index}[] = {{')
            raw = dump.read(start, end-start)
            for offset in range(0, len(raw), 20):
                rows.append('    '+','.join(hex(b) for b in raw[offset:offset+20])+',')
            rows.append('};')
        rows.append('static const unsigned char *fixtures[] = {' +
                    ','.join(f'fixture_{i}' for i in range(len(SITES))) + '};')
        args.fixtures.parent.mkdir(parents=True, exist_ok=True)
        args.fixtures.write_text('\n'.join(rows)+'\n', encoding='utf-8')
    else:
        path.write_text(render(), encoding='utf-8')
    print(f'Wrote {len(SITES)} probe '+('fixtures.' if args.fixtures else 'fingerprints.'))
