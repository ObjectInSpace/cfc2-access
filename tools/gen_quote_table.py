"""Emit src/quote_table.h -- CVS2's 384 win quotes as a C table.

WHY A GENERATED HEADER AND NOT A RUNTIME READ
---------------------------------------------
The quote text is GUEST data: it lives in the emulated machine's arena, is
reached through the archive's own entry table, and is read by emulated SH-4
code. Reading it live would mean resolving that chain every time a quote is
displayed, on the speech worker, during the few seconds the screen is up.

The text is also CONSTANT -- it ships in the archive and never changes. So it
is decoded ONCE, offline, by the audited decoder in tools/cvs2_quotes.py, and
compiled in. The runtime reader then needs only two small integers from live
memory (character ID, quote index) and speaks a string it already holds.

⭐ This also means the mod never dereferences a guest pointer to produce
speech. Everything it reads at runtime is a byte at a validated offset.

THE CONTROLS ARE THE DECODER'S OWN. This script imports cvs2_quotes and runs
its self_test() before writing anything -- the same positive control (five
phrases confirmed live in the running game), the same multi-line join check,
the same non-printable and distinctness tests. If that fails, nothing is
written. A generator that emits a table from a decoder it did not verify is
exactly the shape of error this project keeps paying for.

⚠ C STRING ESCAPING IS A CORRECTNESS ISSUE HERE, not a cosmetic one. Quotes
contain apostrophes, double quotes and backslashes; one unescaped character
silently shifts every following string. escape() handles them and emit_check()
re-parses the generated file to confirm the count survived.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cvs2_quotes

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   '..', 'src', 'quote_table.h')


def escape(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif 32 <= ord(ch) <= 126:
            out.append(ch)
        else:
            # The decoder's own control rejects these, so reaching here is a bug.
            raise ValueError("non-printable %r in %r" % (ch, s))
    return ''.join(out)


def main():
    blob = cvs2_quotes.extract_blob(cvs2_quotes.DEFAULT_ARC)
    region = cvs2_quotes.load_region(blob)
    quotes = cvs2_quotes.decode(region)

    print("running the decoder's own controls before writing:")
    if not cvs2_quotes.self_test(quotes):
        print("\nDECODER CONTROLS FAILED -- refusing to write %s" % OUT)
        return 2

    n_chars = len(quotes)
    n_each = len(quotes[0])

    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write("/* GENERATED by tools/gen_quote_table.py -- do not edit.\n"
                " *\n"
                " * CVS2's win quotes: %d characters x %d, decoded from\n"
                " * bin/cvs2 in arc/pc/game_10.arc by tools/cvs2_quotes.py.\n"
                " *\n"
                " * Indexed [character ID][quote index]. The character ID is\n"
                " * the same roster order src/cvs2_select.c already uses.\n"
                " *\n"
                " * ASCII only -- the generator refuses any other byte, so\n"
                " * these are safe to widen for speech without a codepage.\n"
                " */\n"
                "#ifndef CFC2_QUOTE_TABLE_H\n"
                "#define CFC2_QUOTE_TABLE_H\n\n"
                "#define CVS2_QUOTE_CHARS   %d\n"
                "#define CVS2_QUOTES_EACH   %d\n\n"
                "static const char *const cvs2_quotes"
                "[CVS2_QUOTE_CHARS][CVS2_QUOTES_EACH] = {\n"
                % (n_chars, n_each, n_chars, n_each))
        for cid, cq in enumerate(quotes):
            f.write("    { /* %d */\n" % cid)
            for q in cq:
                f.write('        "%s",\n' % escape(q))
            f.write("    },\n")
        f.write("};\n\n#endif\n")

    # Re-parse what was actually written: escaping errors show up as a changed
    # string count, which is the failure mode that would otherwise be silent.
    with open(OUT, encoding='ascii') as f:
        body = f.read()
    got = body.count('",\n')
    want = n_chars * n_each
    print("\n  wrote %s" % os.path.normpath(OUT))
    print("  strings re-parsed from the written file: %d (want %d)" % (got, want))
    if got != want:
        print("    FAIL -- escaping changed the string count")
        return 2
    print("  OK -- table written and re-parsed clean")
    return 0


if __name__ == '__main__':
    sys.exit(main())
